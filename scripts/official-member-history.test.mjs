import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import test from 'node:test';
import {transform} from 'esbuild';
const {code}=await transform(await readFile(new URL('../lib/official-member-history.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm'});
const {prepareOfficialMemberHistory}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const scope={membershipId:'membership1',userId:'member1',classId:'aikido'};
test('PDF history stays bound to selected member, class and membership without changing unknown exam outcomes',()=>{
 const exams=[{result_id:'lost',class_id:'aikido',assessment_date:null,outcome:'lost_record'},{result_id:'dated',class_id:'aikido',assessment_date:'2020-02-03',outcome:'recorded_grade'},{result_id:'other',class_id:'karate',assessment_date:'2000-01-01',outcome:'pass'}];
 const transfers=[{request_id:'included',membership_id:'membership1',class_id:'aikido',effective_date:'2021-05-01',status:'approved',execution_state:'failed',from_dojo_name:'North',to_dojo_name:'South'},{request_id:'excluded',membership_id:'another',class_id:'aikido',effective_date:'2020-01-01',status:'pending'}];
 const requests=[{id:'own',user_id:'member1',class_id:'aikido',created_at:'2022-04-03',status:'approved',from_dojo:null,to_dojo:{name:'South'}},{id:'other-member',user_id:'member2',class_id:'aikido',created_at:'2022-01-01',status:'pending'}];
 const before=JSON.stringify({exams,transfers,requests});
 const result=prepareOfficialMemberHistory(scope,exams,transfers,requests);
 assert.deepEqual(result.assessment_history.map(x=>[x.result_id,x.outcome]),[['dated','recorded_grade'],['lost','lost_record']]);
 assert.deepEqual(result.transfer_history.map(x=>[x.id,x.status,x.dateLabel]),[['admin:included','failed','Effective'],['member:own','approved','Requested']]);
 assert.equal(result.transfer_history[1].fromDojo,'Unknown');
 assert.equal(JSON.stringify({exams,transfers,requests}),before);
});
test('no transfer data produces no transfer section data',()=>{
 assert.deepEqual(prepareOfficialMemberHistory(scope,[],[],[]),{assessment_history:[],transfer_history:[]});
});
test('PDF preserves top audit metadata and removes duplicated final report section',async()=>{
 const source=await readFile(new URL('../components/MemberRecordPDF.tsx',import.meta.url),'utf8');
 assert.doesNotMatch(source,/REPORT INFORMATION/);
 assert.equal([...source.matchAll(/Generated By/g)].length,1);
 assert.match(source,/record\.transfer_history\?\.length/);
 assert.match(source,/assessmentOutcomeLabel\(item.outcome\)/);
 assert.match(source,/Unknown \/ incomplete/);
});
