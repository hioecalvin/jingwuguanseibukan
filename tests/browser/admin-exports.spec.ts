test('Archive remains view-only and exposes its complete record without a download action', async ({ page }) => {
  await page.goto(`${NAV_ORIGIN}/admin-archive`);
  await expect(page.getByRole('heading', { name: 'Archive', exact: true })).toBeVisible();
  await expect(page.getByText('JS-AIK-2026-0001', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: /export|download/i })).toHaveCount(0);

  await page.getByRole('button', { name: 'View Record' }).evaluate(button => (button as HTMLButtonElement).click());
  const dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('View only');
  await expect(dialog).toContainText('Fixture Member');
  await expect(dialog).toContainText('A12345');
  await expect(dialog.getByRole('button', { name: /export|download/i })).toHaveCount(0);
});
