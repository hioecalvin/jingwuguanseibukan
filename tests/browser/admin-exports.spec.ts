import fs from 'node:fs';
import * as XLSX from 'xlsx';

import { test, expect } from './fixtures';
import { NAV_ORIGIN } from '../../scripts/browser-smoke-config.mjs';

function workbookRows(downloadPath: string, sheetName: string) {
  const workbook = XLSX.readFile(downloadPath);
  expect(workbook.SheetNames).toEqual([sheetName]);
  return XLSX.utils.sheet_to_json<Record<string, string | number>>(
    workbook.Sheets[sheetName],
    { range: 2 },
  );
}

test('Certificates exports the visible audit history as a real Excel download', async ({ page }) => {
  await page.goto(`${NAV_ORIGIN}/admin-certificates`);
  await expect(page.getByRole('heading', { name: 'Certificate History' })).toBeVisible();
  await expect(page.getByText('JS-AIK-2026-0001', { exact: true })).toBeVisible();

  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Excel' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('Certificate-History.xlsx');
  const downloadPath = await download.path();
  expect(downloadPath).not.toBeNull();
  expect(fs.statSync(downloadPath!).size).toBeGreaterThan(1_000);

  const rows = workbookRows(downloadPath!, 'Certificates');
  expect(rows).toHaveLength(1);
  expect(rows[0]).toMatchObject({
    'Certificate Number': 'JS-AIK-2026-0001',
    'Member ID': 'JS0001',
    'Aikikai Registration Number': 'A12345',
    'Member Name': 'Fixture Member',
    Class: 'Aikido',
    Status: 'Valid',
    'Total Prints': 1,
  });
});

