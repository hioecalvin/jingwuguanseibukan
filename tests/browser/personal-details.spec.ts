import {test,expect} from './fixtures';
import {NAV_ORIGIN} from '../../scripts/browser-smoke-config.mjs';
test('member saves and clears their private emergency contact',async({page})=>{
 await page.goto(NAV_ORIGIN+'/emergency-contact');
 await page.getByRole('button',{name:'Emergency contact',exact:true}).click();
 await page.getByRole('button',{name:'Edit emergency contact'}).click();
 await page.getByLabel('Emergency contact name',{exact:true}).fill('Trusted Person');
 await page.getByLabel('Relation',{exact:true}).fill('Sibling');
 await page.getByLabel('Emergency contact email',{exact:true}).fill('contact@example.invalid');
 await page.getByLabel('Emergency contact phone number',{exact:true}).fill('08123456789');
 await page.getByRole('button',{name:'Save emergency contact'}).click();
 await expect(page.getByRole('status')).toHaveText('Emergency contact saved.');
 await expect(page.getByText('Trusted Person',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Edit emergency contact'}).click();
 for(const label of ['Emergency contact name','Relation','Emergency contact email','Emergency contact phone number'])await page.getByLabel(label,{exact:true}).fill('');
 await page.getByRole('button',{name:'Save emergency contact'}).click();
 await expect(page.getByText('Not provided',{exact:true})).toHaveCount(4);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('emergency contact conflict keeps edits until reload',async({page})=>{
 await page.goto(NAV_ORIGIN+'/emergency-contact?conflict=1');
 await page.getByRole('button',{name:'Emergency contact',exact:true}).click();
 await page.getByRole('button',{name:'Edit emergency contact'}).click();
 await page.getByLabel('Emergency contact name',{exact:true}).fill('Keep my entry');
 await page.getByRole('button',{name:'Save emergency contact'}).click();
 await expect(page.getByRole('alert')).toContainText('changed elsewhere');
 await expect(page.getByLabel('Emergency contact name',{exact:true})).toHaveValue('Keep my entry');
 await page.getByRole('button',{name:'Reload saved emergency contact'}).click();
 await expect(page.getByText('Not provided',{exact:true})).toHaveCount(4);
});
test('Super Admin edits details while claimed email stays pending, with audit',async({page})=>{
 await page.goto(NAV_ORIGIN+'/personal-details');
 await page.getByRole('button',{name:'Edit personal details',exact:true}).click();
 await page.getByLabel('Name',{exact:true}).fill('Corrected Member');
 await page.getByLabel('Date of birth',{exact:true}).fill('1996-11-15');
 await page.getByLabel('Email',{exact:true}).fill('replacement@example.invalid');
 await page.getByLabel('Phone number',{exact:true}).fill('62822222222');
 await page.getByRole('button',{name:'Save personal details'}).click();
 await expect(page.getByRole('status')).toContainText('Verify the new email');
 await page.getByRole('button',{name:'Edit personal details',exact:true}).click();
 await expect(page.getByLabel('Name',{exact:true})).toHaveValue('Corrected Member');
 await expect(page.getByLabel('Email',{exact:true})).toHaveValue('original@example.invalid');
 await expect(page.getByText('Email verification pending: replacement@example.invalid')).toBeVisible();
 await page.getByRole('button',{name:'Personal detail history'}).click();
 await page.locator('summary').click();
 await expect(page.getByText('Existing Member → Corrected Member')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('personal edit conflict preserves entered values and forbidden access reveals none',async({page})=>{
 await page.goto(NAV_ORIGIN+'/personal-details?conflict=1');
 await page.getByRole('button',{name:'Edit personal details',exact:true}).click();
 await page.getByLabel('Name',{exact:true}).fill('Keep my correction');
 await page.getByRole('button',{name:'Save personal details'}).click();
 await expect(page.getByRole('alert')).toContainText('reload');
 await expect(page.getByLabel('Name',{exact:true})).toHaveValue('Keep my correction');
 await page.goto(NAV_ORIGIN+'/personal-details?forbidden=1');
 await page.getByRole('button',{name:'Edit personal details',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('Super Admin access');
 await expect(page.getByLabel('Email',{exact:true})).toHaveCount(0);
});
test('claim lists separate pending claims and paginate verified accounts by 50',async({page})=>{
 await page.goto(NAV_ORIGIN+'/claim-lists');
 await expect(page.getByRole('heading',{name:'Waiting for Confirmation'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Verified Accounts'})).toBeVisible();
 const accounts=page.getByRole('list',{name:'Verified member accounts'});
 await expect(accounts.getByRole('listitem')).toHaveCount(50);
 await expect(accounts.getByRole('link').first()).toHaveAttribute('href','/members/JS-0001');
 await page.getByRole('button',{name:'Next 50'}).click();
 await expect(accounts.getByRole('listitem')).toHaveCount(1);
 await expect(accounts.getByRole('link')).toHaveAttribute('href','/members/JS-0051');
 await expect(page.getByRole('button',{name:'Next 50'})).toBeDisabled();
 await page.getByRole('button',{name:'Previous 50'}).click();
 await expect(accounts.getByRole('listitem')).toHaveCount(50);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
